#!/usr/bin/env python3
"""Render a subset of a GVSoC architecture diagram, optionally highlighting paths.

The input is the Graphviz file generated by `gvrun --target <t> diagram`.

Usage:
    arch_view.py architecture.dot out.png --keep fc,fc_icache,ll_ico,...
                 [--path COLOR:node,node,...] [--title TEXT] [--rankdir LR] [--dpi 150]

Nodes are given by their short GVSoC name (the first line of their label),
e.g. "fc", "ll_ico", "priv0". With --path, edges along each listed chain are
drawn in COLOR and every other edge is dimmed. --path can be repeated.
"""

import argparse
import re
import subprocess
import sys

NODE_RE = re.compile(r'^\s*(\w+) \[label="([^"\\]+)')
EDGE_RE = re.compile(r'^(\s*)(\w+) -> (\w+) \[(.*)\];\s*$')
DIM = '#c8c8c8'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('dot')
    parser.add_argument('out')
    parser.add_argument('--keep', required=True, help='comma-separated short node names')
    parser.add_argument('--path', action='append', default=[], help='COLOR:node,node,...')
    parser.add_argument('--title', default=None)
    parser.add_argument('--rankdir', default=None)
    parser.add_argument('--dpi', default='150')
    args = parser.parse_args()

    lines = open(args.dot).read().splitlines()

    # Map short names to node ids
    ids = {}
    for line in lines:
        m = NODE_RE.match(line)
        if m:
            # "l_shared x12" -> "l_shared". On duplicates, prefer the SoC instance
            name = m.group(2).split()[0]
            if name not in ids or m.group(1).startswith('chip_soc_'):
                ids[name] = m.group(1)

    def node_id(name):
        if name not in ids:
            sys.exit(f'Unknown node: {name} (known: {", ".join(sorted(ids))})')
        return ids[name]

    keep = {node_id(n) for n in args.keep.split(',')}

    highlight = {}
    for spec in args.path:
        color, chain = spec.split(':', 1)
        nodes = [node_id(n) for n in chain.split(',')]
        for a, b in zip(nodes, nodes[1:]):
            highlight[(a, b)] = color

    out = []
    for line in lines:
        m = NODE_RE.match(line)
        if m:
            if m.group(1) in keep:
                out.append(line)
            continue
        m = EDGE_RE.match(line)
        if m:
            indent, a, b, attrs = m.groups()
            if a not in keep or b not in keep:
                continue
            if highlight:
                attrs = re.sub(r'(color|penwidth|style)="?[^",]*"?,?\s*', '', attrs)
                if (a, b) in highlight:
                    attrs = f'color="{highlight[(a, b)]}", penwidth=3.0, ' + attrs
                else:
                    attrs = f'color="{DIM}", penwidth=1.0, ' + attrs
            out.append(f'{indent}{a} -> {b} [{attrs}];')
            continue
        if args.title is not None and line.strip().startswith('label="') and 'Architecture Diagram' in line:
            line = re.sub(r'label="[^"]*"', 'label="%s"' % args.title, line)
        if args.rankdir and line.strip().startswith('rankdir='):
            line = f'    rankdir={args.rankdir};'
        out.append(line)

    # Drop the legend, it describes edge colors that may have been overridden
    text = '\n'.join(out)
    text = re.sub(r'\n\s*subgraph cluster_legend \{.*?\n    \}', '', text, flags=re.S)

    subprocess.run(['dot', '-Tpng', f'-Gdpi={args.dpi}', '-o', args.out],
                   input=text, text=True, check=True)


if __name__ == '__main__':
    main()
